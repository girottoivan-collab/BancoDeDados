SELECT
    TABSCHEMA,
    TABNAME
FROM
    SYSCAT.TABLES
WHERE
    TABSCHEMA = 'TMP'
AND TABNAME = 'LOG_REPROCESSA_DTFIM'
~

SELECT
    COLNO,
    COLNAME,
    TYPENAME,
    LENGTH,
    NULLS
FROM
    SYSCAT.COLUMNS
WHERE
    TABSCHEMA = 'TMP'
AND TABNAME = 'LOG_REPROCESSA_DTFIM'
ORDER BY
    COLNO
~

SELECT
    ROUTINESCHEMA,
    ROUTINENAME,
    VALID
FROM
    SYSCAT.ROUTINES
WHERE
    ROUTINESCHEMA = 'DBA'
AND ROUTINENAME IN (
    'SP_REPROCESSA_DTFIM_ESTSIN_TMP',
    'SP_REPROCESSA_DTFIM_CONSAL_TMP',
    'SP_REPROCESSA_DTFIM_MOVCUS_TMP',
    'SP_REPROCESSA_DTFIM_PROCUS_TMP'
)
ORDER BY
    ROUTINENAME
~

