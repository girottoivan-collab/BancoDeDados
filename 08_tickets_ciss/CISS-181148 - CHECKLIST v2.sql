COMMENT ON COLUMN TAREFA.CHECKLIST_SECAO_PERGUNTA.NRPONTOCORTE IS 'Valor de corte utilizado apenas quando TPRESPOSTA = Escala (2). Respostas com NRRESPOSTA abaixo deste valor caracterizam não conformidade.';
COMMENT ON COLUMN TAREFA.CHECKLIST_SECAO_PERGUNTA.FGEXIGEFOTO IS 'Flag booleana que indica se a pergunta exige o anexo de foto na resposta quando esta caracteriza não conformidade. Não se aplica quando TPRESPOSTA = Texto Livre (4). 0 - Não exige / 1 - Exige';
COMMENT ON COLUMN TAREFA.CHECKLIST_SECAO_PERGUNTA.FGEXIGECOMENTARIO IS 'Flag booleana que indica se a pergunta exige comentário na resposta quando esta caracteriza não conformidade. Não se aplica quando TPRESPOSTA = Texto Livre (4). 0 - Não exige / 1 - Exige';
COMMENT ON COLUMN TAREFA.CHECKLIST_SECAO_PERGUNTA.FGATIVO IS 'Flag booleana da Pergunta. 0 - Inativo / 1 - Ativo';

