    CONSTRAINT CKT_CHECKLIST_SECAO_PERGUNTA_FGEXIGEFOTO CHECK (FGEXIGEFOTO IN (0, 1)),
    CONSTRAINT CKT_CHECKLIST_SECAO_PERGUNTA_FGEXIGECOMENTARIO CHECK (FGEXIGECOMENTARIO IN (0, 1)),
    CONSTRAINT CKT_CHECKLIST_SECAO_PERGUNTA_FGATIVO CHECK (FGATIVO IN (0, 1))
