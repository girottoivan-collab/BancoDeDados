COMMENT ON COLUMN TAREFA.CHECKLIST_SECAO_PERGUNTA.NRORDEM IS 'Ordem de exibição da Pergunta dentro da Seção.';
COMMENT ON COLUMN TAREFA.CHECKLIST_SECAO_PERGUNTA.TPRESPOSTA IS 'Tipo de resposta esperado para a pergunta, que define onde o valor da resposta é armazenado. 1 - Sim/Não (usa NRRESPOSTA) / 2 - Escala (usa NRRESPOSTA e o NRPONTOCORTE da pergunta) / 3 - Múltipla Escolha (usa AGENDAMENTO_EXECUCAO_CHECKLIST_RESPOSTA_OPCAO) / 4 - Texto Livre (usa DSRESPOSTA)';
