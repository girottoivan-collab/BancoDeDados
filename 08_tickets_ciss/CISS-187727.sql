CREATE OR REPLACE FUNCTION DBA.FN_VALIDA_NCM02023000 (
    P_IDPRODUTO INTEGER,
    P_IDSUBPRODUTO INTEGER
)
RETURNS CHAR(1)
LANGUAGE SQL
READS SQL DATA
RETURN CASE
    WHEN EXISTS (
        SELECT 1
        FROM DBA.PRODUTO_GRADE AS PG
        WHERE PG.IDPRODUTO = P_IDPRODUTO
          AND PG.IDSUBPRODUTO = P_IDSUBPRODUTO
          AND PG.NCM = '02023000'
    ) THEN 'T'
    ELSE 'F'
END
GO
CREATE OR REPLACE TRIGGER DBA.TR_BI_PTRIB_NCM02023000 BEFORE INSERT ON DBA.PRODUTO_TRIBUTACAO
REFERENCING NEW AS N
FOR EACH ROW
MODE DB2SQL
WHEN (DBA.FN_VALIDA_NCM02023000(N.IDPRODUTO, N.IDSUBPRODUTO) = 'T')
BEGIN ATOMIC
    SET N.TIPOSITTRIBSAI = 'T';
    SET N.IDSITTRIBSAI = 0;
    SET N.PERICMSAI = 4.5;
    SET N.PERREDTRIBSAI = 0;
END
GO
