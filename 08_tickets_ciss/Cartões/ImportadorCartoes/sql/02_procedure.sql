-- Executar com terminador @. A chamada deve usar conexao dedicada: ha commits internos.
CREATE OR REPLACE PROCEDURE TMP.SP_PROCESSAR_CARTOES_MOVIMENTO ()
 LANGUAGE SQL
 MODIFIES SQL DATA
 DYNAMIC RESULT SETS 1
 COMMIT ON RETURN NO
BEGIN
 DECLARE V_MAX BIGINT DEFAULT 0;
 DECLARE V_LAST BIGINT DEFAULT 0;
 DECLARE V_ID BIGINT;
 DECLARE V_LOTE INTEGER DEFAULT 0;
 DECLARE V_LOTES INTEGER DEFAULT 0;
 DECLARE V_LIDOS INTEGER DEFAULT 0;
 DECLARE V_S0 INTEGER DEFAULT 0;
 DECLARE V_S1 INTEGER DEFAULT 0;
 DECLARE V_S2 INTEGER DEFAULT 0;
 DECLARE V_S3 INTEGER DEFAULT 0;
 DECLARE V_PENDENTES INTEGER DEFAULT 0;
 DECLARE V_ESTAB VARCHAR(40);
 DECLARE V_CNPJ VARCHAR(14);
 DECLARE V_AUT VARCHAR(64);
 DECLARE V_NSU VARCHAR(64);
 DECLARE V_NSU_NUM DECIMAL(18,0);
 DECLARE V_MAQUINA VARCHAR(64);
 DECLARE V_DATA DATE;
 DECLARE V_STATUS SMALLINT;
 DECLARE V_ENCONTRADOS INTEGER;
 DECLARE V_PRECISAM INTEGER;
 DECLARE V_ALTERADOS INTEGER;
 DECLARE V_STATE CHAR(5);
 DECLARE V_CODE INTEGER;
 DECLARE V_MESSAGE VARCHAR(32672);
 DECLARE SQLSTATE CHAR(5) DEFAULT '00000';
 DECLARE SQLCODE INTEGER DEFAULT 0;
 DECLARE C_RESULT CURSOR WITH RETURN TO CALLER FOR
  SELECT V_LIDOS AS LIDOS, V_S0 AS COM_ERRO, V_S1 AS ALTERADOS,
         V_S2 AS NAO_ALTERADOS, V_S3 AS NAO_ENCONTRADOS,
         V_PENDENTES AS MANTIDOS_PENDENTES, V_LOTES AS LOTES_COMMITADOS
  FROM SYSIBM.SYSDUMMY1;
 DECLARE EXIT HANDLER FOR SQLEXCEPTION
 BEGIN
  ROLLBACK;
  RESIGNAL;
 END;

 SELECT COALESCE(MAX(ID),0) INTO V_MAX FROM TMP.CARTOES_MOVIMENTO;
 LOTES: WHILE V_LAST < V_MAX DO
  -- Serializa apenas os processadores durante cada lote. Nao bloqueia novas importacoes.
  LOCK TABLE TMP.CARTOES_MOVIMENTO_PROCESSADOS IN EXCLUSIVE MODE;
  SET V_LOTE = 0;
  LINHAS: WHILE V_LOTE < 1000 AND V_LAST < V_MAX DO
   SELECT MIN(ID) INTO V_ID FROM TMP.CARTOES_MOVIMENTO WHERE ID > V_LAST AND ID <= V_MAX;
   IF V_ID IS NULL THEN LEAVE LINHAS; END IF;
   SET V_LAST = V_ID;
   SET V_LOTE = V_LOTE + 1;
   SET V_LIDOS = V_LIDOS + 1;
   SET V_STATUS = -1;
   SET V_ENCONTRADOS = 0;
   SET V_ALTERADOS = 0;
   SAVEPOINT SP_CARTAO ON ROLLBACK RETAIN CURSORS;
   BEGIN
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
     GET DIAGNOSTICS EXCEPTION 1 V_MESSAGE = MESSAGE_TEXT;
     SET (V_STATE,V_CODE) = (SQLSTATE,SQLCODE);
     ROLLBACK TO SAVEPOINT SP_CARTAO;
     INSERT INTO TMP.CARTOES_MOVIMENTO_PROCESSADOS
      (ID,ESTABELECIMENTO,CNPJ,AUTORIZACAO,NSU,NUMERO_MAQUINA,DTMOVIMENTO,ARQUIVO_HASH,ABA,LINHA,IMPORTADO_EM,STATUS,QTD_ENCONTRADOS,QTD_ALTERADOS,SQLSTATE_ERRO,SQLCODE_ERRO,MENSAGEM_ERRO)
     SELECT ID,ESTABELECIMENTO,CNPJ,AUTORIZACAO,NSU,NUMERO_MAQUINA,DTMOVIMENTO,ARQUIVO_HASH,ABA,LINHA,IMPORTADO_EM,0,V_ENCONTRADOS,0,V_STATE,V_CODE,SUBSTR(RTRIM(V_MESSAGE),1,2048)
      FROM TMP.CARTOES_MOVIMENTO WHERE ID=V_ID;
     DELETE FROM TMP.CARTOES_MOVIMENTO WHERE ID=V_ID;
     SET V_S0 = V_S0 + 1;
    END;

    SELECT ESTABELECIMENTO,CNPJ,AUTORIZACAO,NSU,NUMERO_MAQUINA,DTMOVIMENTO
     INTO V_ESTAB,V_CNPJ,V_AUT,V_NSU,V_MAQUINA,V_DATA
     FROM TMP.CARTOES_MOVIMENTO WHERE ID=V_ID WITH RS;
    IF V_DATA IS NULL THEN SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT='DTMOVIMENTO ausente. Recuperar data da planilha original.'; END IF;
    IF NOT REGEXP_LIKE(TRIM(V_NSU),'^[0-9]{1,18}$') THEN SIGNAL SQLSTATE '75002' SET MESSAGE_TEXT='NSU invalido para IDNSUHOST DECIMAL(18,0).'; END IF;
    SET V_NSU_NUM = DECIMAL(TRIM(V_NSU),18,0);
    SELECT COUNT(*),COALESCE(SUM(CASE WHEN CODTERMINAL IS NULL OR TRIM(CODTERMINAL)='' OR UPPER(TRIM(CODTERMINAL)) IN ('NAO IDENTIFICADO','NÃO IDENTIFICADO') THEN 1 ELSE 0 END),0)
     INTO V_ENCONTRADOS,V_PRECISAM
     FROM DBA.CLW_RETORNO_CONTAS_RECEBER
     WHERE IDAUTORIZACAO=V_AUT AND IDNSUHOST=V_NSU_NUM AND CODESTABELECIMENTO=V_ESTAB AND CNPJ=V_CNPJ WITH RS;
    IF V_ENCONTRADOS > 0 THEN
     IF V_PRECISAM > 0 THEN
      IF LENGTH(TRIM(V_MAQUINA))=0 OR LENGTH(V_MAQUINA)>40 THEN SIGNAL SQLSTATE '75003' SET MESSAGE_TEXT='NUMERO_MAQUINA vazio ou maior que CODTERMINAL (40 caracteres).'; END IF;
      UPDATE DBA.CLW_RETORNO_CONTAS_RECEBER SET CODTERMINAL=V_MAQUINA
       WHERE IDAUTORIZACAO=V_AUT AND IDNSUHOST=V_NSU_NUM AND CODESTABELECIMENTO=V_ESTAB AND CNPJ=V_CNPJ
        AND (CODTERMINAL IS NULL OR TRIM(CODTERMINAL)='' OR UPPER(TRIM(CODTERMINAL)) IN ('NAO IDENTIFICADO','NÃO IDENTIFICADO'));
      GET DIAGNOSTICS V_ALTERADOS = ROW_COUNT;
     END IF;
     IF V_ALTERADOS > 0 THEN SET V_STATUS=1; ELSE SET V_STATUS=2; END IF;
    ELSEIF V_DATA < CURRENT DATE - 5 DAYS THEN
     SET V_STATUS=3;
    ELSE
     SET V_PENDENTES=V_PENDENTES+1;
    END IF;

    IF V_STATUS >= 0 THEN
     INSERT INTO TMP.CARTOES_MOVIMENTO_PROCESSADOS
      (ID,ESTABELECIMENTO,CNPJ,AUTORIZACAO,NSU,NUMERO_MAQUINA,DTMOVIMENTO,ARQUIVO_HASH,ABA,LINHA,IMPORTADO_EM,STATUS,QTD_ENCONTRADOS,QTD_ALTERADOS)
     SELECT ID,ESTABELECIMENTO,CNPJ,AUTORIZACAO,NSU,NUMERO_MAQUINA,DTMOVIMENTO,ARQUIVO_HASH,ABA,LINHA,IMPORTADO_EM,V_STATUS,V_ENCONTRADOS,V_ALTERADOS
      FROM TMP.CARTOES_MOVIMENTO WHERE ID=V_ID;
     DELETE FROM TMP.CARTOES_MOVIMENTO WHERE ID=V_ID;
     IF V_STATUS=1 THEN SET V_S1=V_S1+1;
     ELSEIF V_STATUS=2 THEN SET V_S2=V_S2+1;
     ELSEIF V_STATUS=3 THEN SET V_S3=V_S3+1; END IF;
    END IF;
   END;
   RELEASE SAVEPOINT SP_CARTAO;
  END WHILE LINHAS;
  COMMIT;
  IF V_LOTE=0 THEN LEAVE LOTES; END IF;
  SET V_LOTES=V_LOTES+1;
 END WHILE LOTES;
 OPEN C_RESULT;
END
