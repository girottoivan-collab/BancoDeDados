-- Apos o timeout, a espera pode ter desaparecido; nenhuma linha nao prova ausencia de disputa anterior.
SELECT
    REQ_APPLICATION_HANDLE AS SESSAO_AGUARDANDO,
    HLD_APPLICATION_HANDLE AS SESSAO_BLOQUEADORA,
    LOCK_OBJECT_TYPE,
    TABSCHEMA,
    TABNAME,
    LOCK_WAIT_ELAPSED_TIME,
    REQ_APPLICATION_NAME,
    HLD_APPLICATION_NAME,
    REQ_STMT_TEXT,
    HLD_CURRENT_STMT_TEXT
FROM SYSIBMADM.MON_LOCKWAITS
WHERE UPPER(COALESCE(REQ_STMT_TEXT, '')) LIKE '%SP_PROCESSAR_CARTOES_MOVIMENTO%'
   OR (TABSCHEMA = 'TMP' AND TABNAME LIKE 'CARTOES%')
   OR (TABSCHEMA = 'DBA' AND TABNAME IN ('CLW_RETORNO_CONTAS_RECEBER', 'BIGSM_CADTERMINAL'))
@
