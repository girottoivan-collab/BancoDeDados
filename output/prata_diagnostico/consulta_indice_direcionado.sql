SELECT
	STATUSDESCRICAO,
	STATUS,
	IDEMPRESA,
	IDPLANILHA,
	IDTITULO,
	CAST(DIGITOTITULO AS INTEGER) AS PARCELA,
	DIGITOTITULO,
	IDCLIFOR,
	NOME,
	SERIENOTA,
	DTMOVIMENTO,
	DTMOVIMENTODETALHES,
	DTVENCIMENTO,
	DTULTIMOPAGAMENTO,
	ORIGEMMOVIMENTO,
	CODAUTORIZACAOSITEF,
	IDADMINISTRADORA,
	DESCRADMINISTRADORA,
	IDBANDEIRA,
	DESCRINSTITUICAO,
	TIPOCARTAO,
	IDNSUHOST,
	NRCARD,
	OBSTITULO,
	PAGAMENTOPARCIAL,
	VALTITULO,
	FLAGBAIXADA,
	DESCRRECEBIMENTO,
	TIPOVENDACARTAO,
	NUMPARCELASADMINISTRADORA,
	NUMNOTA,
	NUMCUPOMFISCAL,
	ORIGEMBAIXA,
	STATUSPARCIAL,
	STATUSDIVERGENTE,
	STATUSOK,
	MAX_PARCELA,
	DETALHES,
	VALSALDOTITULO,
	VALLIQUIDOPAGO,
	ORIGEMBAIXADETALHE,
	IDCONCILIACAO,
	IDCONCIFLEX,
	CONFIRMADO
FROM (
	SELECT
		CASE
			WHEN STATUS = 'CO' OR ('CP' = 'CV' AND ORIGEMBAIXA = 'SIT' AND STATUS <> 'PD') THEN
				CASE WHEN 'CP' = 'CP' AND ORIGEMBAIXA = 'TES' THEN
					'CT'
				ELSE
					'CO'
				END
			ELSE
				STATUS
		END AS STATUSDESCRICAO,
		CASE
			WHEN STATUS IN ('CO', 'CT') OR ('CP' = 'CV' AND ORIGEMBAIXA = 'SIT' AND STATUS <> 'PD') THEN
				CAST('Imagens\green.gif' AS VARCHAR(40))
			WHEN STATUS = 'PD'
				THEN CAST('Imagens\yellow.gif' AS VARCHAR(40))
			ELSE
				CAST('Imagens\red.gif' AS VARCHAR(40))
		END AS STATUS,
		IDEMPRESA,
		IDPLANILHA,
		IDTITULO,
		DIGITOTITULO,
		IDCLIFOR,
		NOME,
		SERIENOTA,
		DTMOVIMENTO,
		DTMOVIMENTODETALHES,
		DTVENCIMENTO,
		DTULTIMOPAGAMENTO,
		ORIGEMMOVIMENTO,
		CODAUTORIZACAOSITEF,
		IDADMINISTRADORA,
		DESCRADMINISTRADORA,
		IDBANDEIRA,
		DESCRINSTITUICAO,
		TIPOCARTAO,
		IDNSUHOST,
		NRCARD,
		OBSTITULO,
		PAGAMENTOPARCIAL,
		VALTITULO,
		FLAGBAIXADA,
		DESCRRECEBIMENTO,
		TIPOVENDACARTAO,
		NUMPARCELASADMINISTRADORA,
		NUMNOTA,
		NUMCUPOMFISCAL,
		ORIGEMBAIXA,
		CAST('Imagens\yellow.gif' AS VARCHAR(40)) AS STATUSPARCIAL,
		CAST('Imagens\red.gif' AS VARCHAR(40)) AS STATUSDIVERGENTE,
		CAST('Imagens\green.gif' AS VARCHAR(40)) AS STATUSOK,
		MAX_PARCELA,
		CAST('Imagens\info.gif' AS VARCHAR(40)) AS DETALHES,
		VALSALDOTITULO,
		VALLIQUIDOPAGO,
		ORIGEMBAIXADETALHE,
		IDCONCILIACAO,
		IDCONCIFLEX,
		CASE
			WHEN TRIM(IDCONCIFLEX) <> '' THEN 'T'
			ELSE 'F'
		END AS CONFIRMADO
	FROM
		(
		SELECT
			CASE
				WHEN 'CP' = 'CP' THEN
					CASE
						WHEN (COALESCE(CR.VALTITULO, 0) - COALESCE(CR.SUMVALPAGAMENTOTITULO, 0)) < 0 THEN
							'PD'
						WHEN CR.FLAGBAIXADA = 'T' THEN
							'CO'
						ELSE
							'NC'
					END
				ELSE
					CASE
						WHEN (
							SELECT
								COUNT(ORIGEMMOVIMENTO)
							FROM
								CONTAS_RECEBER_BAIXAS AS BAIXA
							WHERE
								CR.IDEMPRESA = BAIXA.IDEMPRESA AND
								CR.IDCLIFOR = BAIXA.IDCLIFOR AND
								CR.IDTITULO = BAIXA.IDTITULO AND
								CR.DIGITOTITULO = BAIXA.DIGITOTITULO AND
								CR.SERIENOTA = BAIXA.SERIENOTA AND
								BAIXA.ORIGEMMOVIMENTO <> 'SIT'
							) > 0 AND CR.FLAGBAIXADA = 'T' THEN
							'CT'
						WHEN COALESCE((
							SELECT
								COUNT(1)
							FROM
								CLW_CONCILIACAO_VENDA CV
							WHERE
								CV.IDEMPRESA = CR.IDEMPRESA AND
								CV.IDTITULO = CR.IDTITULO AND
								CV.DIGITOTITULO = CR.DIGITOTITULO AND
								CV.SERIENOTA = CR.SERIENOTA AND
								CV.IDCLIFOR = CR.IDCLIFOR
							), 0) > 0 AND CR.FLAGBAIXADA = 'T' THEN
								'CO'
						ELSE
							'NC'
					END
				END AS STATUS,
			CR.IDEMPRESA,
			CR.IDPLANILHA,
			CR.IDTITULO,
			CR.DIGITOTITULO,
			CR.IDCLIFOR,
			CLIENTE.NOME AS NOME,
			CR.SERIENOTA,
			CR.DTMOVIMENTO,
			NOTAS.DTMOVIMENTO AS DTMOVIMENTODETALHES,
			CR.DTVENCIMENTO,
			CR.ORIGEMMOVIMENTO,
			CR.CODAUTORIZACAOSITEF,
			CR.IDADMINISTRADORA,
			ADM.DESCRADMINISTRADORA,
			CR.IDBANDEIRA,
			BANDEIRA.DESCRINSTITUICAO,
			CR.TIPOCARTAO,
			CR.IDNSUHOST,
			CR.NRCARD,
			CR.OBSTITULO,
			CRB.VALPAGAMENTOTITULO AS PAGAMENTOPARCIAL,
			CR.VALTITULO,
			CR.FLAGBAIXADA,
			FORMA_PAGREC.DESCRRECEBIMENTO,
			CR.SUMVALPAGAMENTOTITULO,
			COALESCE(CRB.DTPAGAMENTO, CR.DTULTIMOPAGAMENTO) AS DTULTIMOPAGAMENTO,
			CASE
				WHEN CR.IDNSUHOST IS NULL OR CR.IDNSUHOST = 0 THEN
					'POS'
				ELSE
					'TEF'
			END AS TIPOVENDACARTAO,
			CR.NUMPARCELASADMINISTRADORA,
			NOTAS.NUMNOTA,
			NOTAS.NUMCUPOMFISCAL,
			MIN(CRB.ORIGEMMOVIMENTO) OVER (PARTITION BY CRB.IDEMPRESA,CRB.IDCLIFOR,CRB.IDTITULO,CRB.DIGITOTITULO,CRB.SERIENOTA) AS ORIGEMBAIXA,
			MAX(CR.DIGITOTITULO) OVER (PARTITION BY CR.IDEMPRESA,CR.IDCLIFOR,CR.IDTITULO,CR.SERIENOTA) AS MAX_PARCELA,
			(COALESCE(CR.VALTITULO, 0) - COALESCE(CR.SUMVALPAGAMENTOTITULO, 0)) AS VALSALDOTITULO,
			CCR.VALLIQUIDOPAGO,
			(
			SELECT
				ORIGEMMOVIMENTO
			FROM
				CONTAS_RECEBER_BAIXAS_DETALHES AS BD
			WHERE
				CR.IDEMPRESA = BD.IDEMPRESA AND
				CR.IDCLIFOR = BD.IDCLIFOR AND
				CR.IDTITULO = BD.IDTITULO AND
				CR.DIGITOTITULO = BD.DIGITOTITULO AND
				CR.SERIENOTA = BD.SERIENOTA
			FETCH FIRST 1 ROWS ONLY
			) AS ORIGEMBAIXADETALHE,
			CRC.IDCONCILIACAO,
			CCR.IDCONCIFLEX
		FROM
			CONTAS_RECEBER AS CR
		JOIN
			CLIENTE_FORNECEDOR AS CLIENTE ON
				CLIENTE.IDCLIFOR = CR.IDCLIFOR
		JOIN
			ADMINISTRADORAS AS ADM ON
				ADM.IDADMINISTRADORA = CR.IDADMINISTRADORA
		JOIN
			ADMINISTRADORAS_BANDEIRA AS BANDEIRA ON
				BANDEIRA.IDEMPRESA = CR.IDEMPRESA AND
				BANDEIRA.IDADMINISTRADORA = CR.IDADMINISTRADORA AND
				BANDEIRA.IDBANDEIRA = CR.IDBANDEIRA
		LEFT JOIN
			FORMA_PAGREC ON
				CR.IDRECEBIMENTO = FORMA_PAGREC.IDRECEBIMENTO
		LEFT JOIN
			NOTAS ON
				NOTAS.IDEMPRESA = CR.IDEMPRESA AND
				NOTAS.IDPLANILHA = CR.IDPLANILHA
		LEFT JOIN
			CONTAS_RECEBER_CONCILIACAO CRC ON
				CRC.IDCLIFOR = CR.IDCLIFOR AND
				CRC.IDEMPRESA = CR.IDEMPRESA AND
				CRC.DIGITOTITULO = CR.DIGITOTITULO AND
				CRC.SERIENOTA = CR.SERIENOTA AND
				CRC.IDTITULO = CR.IDTITULO
		LEFT JOIN
			CONCIFLEX_CONTAS_RECEBER CCR ON
				CCR.IDCONCILIACAO = CRC.IDCONCILIACAO
		LEFT JOIN
			CONTAS_RECEBER_BAIXAS CRB ON
				CR.IDEMPRESA = CRB.IDEMPRESA AND
				CR.IDCLIFOR = CRB.IDCLIFOR AND
				CR.IDTITULO = CRB.IDTITULO AND
				CR.DIGITOTITULO = CRB.DIGITOTITULO AND
				CR.SERIENOTA = CRB.SERIENOTA
		WHERE
			CR.IDEMPRESA IN (1) AND
			(CR.DTVENCIMENTO BETWEEN '18/10/2026' AND '18/10/2026') AND
			(CR.ORIGEMMOVIMENTO IN('SIT', 'TES')) AND
			(BANDEIRA.IDADMINISTRADORA = 99)
) AS TMP
) AS TMP2
WHERE
	2 = 2 AND
	('TD' = 'TD')
FOR READ ONLY
