-- Executar apos criar WMS.TB_WMS_PALLET_PEDIDO_PRODUTO.
-- Db2 CLP: db2 -td@ -f 05_wms/tr_bi_wms_pallet_pedido_produto.sql
CREATE TRIGGER WMS.TR_BI_WMS_PALLET_PEDPROD
NO CASCADE BEFORE INSERT ON WMS.TB_WMS_PALLET_PEDIDO_PRODUTO
REFERENCING NEW AS N
FOR EACH ROW
SET N.IDPRODUTO = (
    SELECT PG.IDPRODUTO
    FROM DBA.PRODUTO_GRADE PG
    WHERE PG.IDSUBPRODUTO = N.IDSUBPRODUTO
)@
