CREATE TABLE WMS.TB_WMS_PALLET (
    IDWMSPALLET INTEGER NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1),
    NRODOCPALLET INTEGER NOT NULL,
    IDEMPRESAORIGEM INTEGER NOT NULL,
    IDEMPRESADESTINO INTEGER,
    IDCLIFORDESTINO INTEGER,
    FLAGPROCESSADO CHAR(1) DEFAULT 'F',
    CONSTRAINT TB_WMS_PALLET_PK PRIMARY KEY (IDWMSPALLET),
    CONSTRAINT TB_WMS_PALLET_UNIQUE UNIQUE (NRODOCPALLET)
)@

CREATE TRIGGER WMS.TR_BI_WMS_PALLET_EMPDEST
NO CASCADE BEFORE INSERT ON WMS.TB_WMS_PALLET
REFERENCING NEW AS N
FOR EACH ROW
WHEN (N.IDCLIFORDESTINO IS NOT NULL)
SET N.IDEMPRESADESTINO = (
    SELECT E.IDEMPRESA
    FROM DBA.CLIENTE_FORNECEDOR CF
    JOIN DBA.EMPRESA E ON E.CNPJ = CF.CNPJCPF
    WHERE CF.IDCLIFOR = N.IDCLIFORDESTINO
      AND TRIM(CF.CNPJCPF) <> ''
)@

CREATE TRIGGER WMS.TR_BU_WMS_PALLET_EMPDEST
NO CASCADE BEFORE UPDATE OF IDCLIFORDESTINO ON WMS.TB_WMS_PALLET
REFERENCING NEW AS N
FOR EACH ROW
SET N.IDEMPRESADESTINO = (
    SELECT E.IDEMPRESA
    FROM DBA.CLIENTE_FORNECEDOR CF
    JOIN DBA.EMPRESA E ON E.CNPJ = CF.CNPJCPF
    WHERE CF.IDCLIFOR = N.IDCLIFORDESTINO
      AND TRIM(CF.CNPJCPF) <> ''
)@
