                SUM(QTDNOTASTIPO) AS QTDNOTAS,
                SUM(XML) AS XML_TOTAL,
                SUM(CAD) AS CAD_TOTAL,
                COUNT(DISTINCT TIPO) AS QTDTIPOS,
