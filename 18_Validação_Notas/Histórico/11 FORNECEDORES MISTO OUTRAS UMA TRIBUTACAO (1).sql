FILTRO AS (
        SELECT A.*
        FROM APURACAO A
        INNER JOIN FORNECEDOR F ON F.IDCLIFOR = A.IDCLIFOR
        WHERE F.XML_TOTAL > 0 AND F.CAD_TOTAL > 0 AND F.QTDTIPOS = 1 AND A.TIPO NOT IN ('ISENTO-40', 'NAOTRIBUTADO-41', 'SUSPENSO-50', 'OUTROS-90', '40-41-50-90')
),
TOTAL_TIPO AS (
        SELECT TIPO, SUM(QTDNOTASTIPO) AS QTDNOTAS
        FROM FILTRO
        GROUP BY TIPO
),
TOTAL_GERAL AS (
        SELECT COALESCE(SUM(QTDNOTAS), 0) AS QTDNOTAS
        FROM TOTAL_TIPO
)
SELECT TIPO, QTDNOTAS, "% QTDNOTAS"
FROM (
        SELECT TT.TIPO, TT.QTDNOTAS,
                DECIMAL(COALESCE((CAST(TT.QTDNOTAS AS DECIMAL(15,6)) / NULLIF(CAST(TG.QTDNOTAS AS DECIMAL(15,6)), 0)) * 100, 0), 15, 2) AS "% QTDNOTAS",
                1 AS ORDEM
        FROM TOTAL_TIPO TT
        CROSS JOIN TOTAL_GERAL TG
        UNION ALL
        SELECT 'TOTAL GERAL', TG.QTDNOTAS, DECIMAL(100, 15, 2), 2
        FROM TOTAL_GERAL TG
)
ORDER BY ORDEM, TIPO;
