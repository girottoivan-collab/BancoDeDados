CREATE OR REPLACE TRIGGER DBA.TR_LEGISLACAO_PISCOFINS_BU
BEFORE UPDATE ON DBA.PISCOFINS_MOVIMENTO
REFERENCING OLD AS O NEW AS N
FOR EACH ROW
BEGIN ATOMIC
    IF (UF_VIGENCIALEGISLACAOPLANILHA(N.IDEMPRESA, N.IDPLANILHA, 1) = 'T') THEN
        SET N.VALPIS = 0.00;
        SET N.VALCOFINS = 0.00;
        SET N.PERPIS = 0.00;
        SET N.PERCOFINS = 0.00;
        SET N.VALBASEPISCOFINS = 0.00;
        SET N.VALDESCONTOPISCOFINS = 0.00;
        SET N.PERBASEPARCIALPISCOFINS = 0.00;
        SET N.PERREDUCAOBASEPISCOFINS = 0.00;
        SET N.VALBASEPISCOFINSPARCIAL = 0.00;
        SET N.VALORADICIONALRATEADOPIS = 0.00;
        SET N.VALORADICIONALRATEADOCOFINS = 0.00;
    END IF;
END
GO
