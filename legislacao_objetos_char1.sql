CREATE OR REPLACE PROCEDURE DBA.SP_INSERT_ESTOQUE(
    IN AL_IDEMPRESA                  INTEGER,
    IN AL_IDEMPRESANOTA              INTEGER,
    IN AL_IDPRODUTO                  INTEGER,
    IN AL_IDSUBPRODUTO               INTEGER,
    IN AL_IDLOCALESTOQUE             INTEGER,
    IN AD_DTMOVIMENTO                DATE,
    IN AD_QTDPRODUTO                 DECIMAL(12,3),
    IN AD_VALTOTLIQUIDO              DECIMAL(15,6),
    IN AS_TIPOCATEGORIA              CHAR,
    IN AS_FLAGMOVCONTABIL            CHAR,
    IN AS_FLAGMOVSALDOPRO            CHAR,
    IN AS_FLAGCALCULOGIRO            CHAR,
    IN AD_VALFRETECONHEC             DECIMAL(15,6),
    IN AL_IDPLANILHA                 INTEGER,
    IN AL_NUMSEQUENCIA               INTEGER,
    IN AL_IDOPERACAO                 INTEGER,
    IN AS_IDLOTE                     VARCHAR(30),
    IN AD_VALICMS                    DECIMAL(15,6),
    IN AD_VALICMFRETE                DECIMAL(15,6),
    IN AS_TIPOSITTRIB                CHAR,
    IN AD_VALICMSUBSTFRONT           DECIMAL(15,6),
    IN AD_VALICMSGARANTIDOINTEGRAL   DECIMAL(15,6),
    IN AS_FLAGMOVCUSMEDIO            CHAR,
    IN AD_VALPIS                     DECIMAL(15,6),
    IN AD_VALCOFINS                  DECIMAL(15,6),
    IN AS_TIPOPISCOFINS              CHAR,
    IN AS_TIPOBAIXAMESTRE            CHAR,
    IN AD_VALTAXASDIVERSAS           DECIMAL(15,6),
    IN AD_VALDIFSUBSTAJUSTADO        DECIMAL(15,6),
    IN AD_VALBONIFICACAO             DECIMAL(15,6),
    IN AS_FLAGPRECOPROMOCAO          CHAR,
    IN AI_IDSITTRIB                  INTEGER
)
BEGIN ATOMIC
    DECLARE LI_IDEMPRESA             INTEGER;
    DECLARE LI_IDEMPRESANOTA         INTEGER;
    DECLARE LI_IDPRODUTO             INTEGER;
    DECLARE LI_IDSUBPRODUTO          INTEGER;
    DECLARE LI_IDLOCALESTOQUE        INTEGER;
    DECLARE LD_DTMOVIMENTO           DATE;
    DECLARE LDE_QTDPRODUTO           DECIMAL(15,3);
    DECLARE LDE_VALTOTLIQUIDO        DECIMAL(15,6);
    DECLARE LS_TIPOCATEGORIA         CHAR;
    DECLARE LS_TIPOITEMCATEGORIA     VARCHAR(3);
    DECLARE LS_FLAGMOVCONTABIL       CHAR;
    DECLARE LS_FLAGMOVSALDOPRO       CHAR;
    DECLARE LS_FLAGCALCULOGIRO       CHAR;
    DECLARE LDE_VALFRETECONHEC       DECIMAL(15,2);
    DECLARE LDE_VALICMS              DECIMAL(15,2);
    DECLARE LI_IDOPERACAO            INTEGER;
    DECLARE LS_FLAGMOVCUSMEDIO       CHAR;
    DECLARE LDE_VALPIS               DECIMAL(15,6);
    DECLARE LDE_VALCOFINS            DECIMAL(15,6);
    DECLARE LS_TIPOPISCOFINS         CHAR;
    DECLARE LS_IDLOTE                CHAR(30);
    DECLARE LDE_VALSFRONTEIRA        DECIMAL(15,6);
    DECLARE LDE_VALGINTEGRAL         DECIMAL(15,6);
    DECLARE LI_IDPLANILHA            INTEGER;
    DECLARE LI_NUMSEQUENCIA          INTEGER;
    DECLARE LDE_VALTAXASDIVERSAS     DECIMAL(15,6);
    DECLARE LDE_VALDIFSUBSTAJUSTADO  DECIMAL(15,6);
    DECLARE LDE_VALBONIFICACAO       DECIMAL(15,6);
    DECLARE LS_FLAGPRECOPROMOCAO     CHAR(1);
    DECLARE LI_IDUSUARIO             INTEGER;
    DECLARE LDE_CMV_OLD              DECIMAL(15,6);
    DECLARE LDE_CMV_NEW              DECIMAL(15,6);
    DECLARE LDE_PERVARIACAO          DECIMAL(15,6);
    DECLARE LS_LOG_VARIACAO_CMV      VARCHAR(3);
    DECLARE LS_NATUREZACOI           CHAR(1);
    SET LS_LOG_VARIACAO_CMV      = (SELECT DADOS FROM DBA.CONFIG_ENTIDADE WHERE ENTIDADE = 'LVC');
    SET LI_IDEMPRESA             = AL_IDEMPRESA;
    SET LI_IDEMPRESANOTA         = AL_IDEMPRESANOTA;
    SET LI_IDPRODUTO             = AL_IDPRODUTO;
    SET LI_IDSUBPRODUTO          = AL_IDSUBPRODUTO;
    SET LI_IDLOCALESTOQUE        = AL_IDLOCALESTOQUE;
    SET LD_DTMOVIMENTO           = AD_DTMOVIMENTO;
    SET LDE_QTDPRODUTO           = AD_QTDPRODUTO;
    SET LDE_VALTOTLIQUIDO        = AD_VALTOTLIQUIDO;
    SET LS_TIPOCATEGORIA         = AS_TIPOCATEGORIA;
    SET LS_FLAGMOVCONTABIL       = AS_FLAGMOVCONTABIL;
    SET LS_FLAGMOVSALDOPRO       = AS_FLAGMOVSALDOPRO;
    SET LS_FLAGCALCULOGIRO       = AS_FLAGCALCULOGIRO;
    SET LDE_VALFRETECONHEC       = AD_VALFRETECONHEC;
    SET LI_IDPLANILHA            = AL_IDPLANILHA;
    SET LI_NUMSEQUENCIA          = AL_NUMSEQUENCIA;
    SET LI_IDOPERACAO            = AL_IDOPERACAO;
    SET LS_IDLOTE                = AS_IDLOTE;
    SET LDE_VALTAXASDIVERSAS     = AD_VALTAXASDIVERSAS;
    SET LS_TIPOITEMCATEGORIA     = (SELECT TIPOITEMCATEGORIA FROM DBA.OPERACAO_INTERNA WHERE IDOPERACAO = LI_IDOPERACAO);
    SET LDE_VALDIFSUBSTAJUSTADO  = AD_VALDIFSUBSTAJUSTADO;
    SET LDE_VALBONIFICACAO       = AD_VALBONIFICACAO;
    SET LS_FLAGPRECOPROMOCAO     = AS_FLAGPRECOPROMOCAO;
    SET LS_NATUREZACOI = UF_GETNATUREZACOI(LI_IDOPERACAO, AS_TIPOCATEGORIA);

    IF (UF_VIGENCIALEGISLACAOPLANILHA(AL_IDEMPRESA, AL_IDPLANILHA, 1) = 'T') THEN
        SET N.AD_VALPIS = 0.00;
        SET N.AD_VALCOFINS = 0.00;
    END IF;

    IF UPPER(LS_FLAGMOVSALDOPRO) = 'F' AND UPPER(LS_TIPOITEMCATEGORIA) NOT IN ('H8','P1','D11','A7', 'A5') THEN
    ELSE
        IF LS_NATUREZACOI = 'S' THEN
            SET LDE_VALICMS = AD_VALICMS;
        ELSE
            SET LDE_VALICMS = AD_VALICMS + AD_VALICMFRETE;
            IF UPPER(AS_TIPOSITTRIB) = 'A' THEN
                SET LDE_VALSFRONTEIRA = AD_VALICMSUBSTFRONT;
                IF LDE_VALSFRONTEIRA IS NULL THEN
                   SET LDE_VALSFRONTEIRA = 0;
                END IF;
            ELSE
                SET LDE_VALSFRONTEIRA = 0;
            END IF;
            IF AD_VALICMSGARANTIDOINTEGRAL > 0 THEN
                SET LDE_VALGINTEGRAL = AD_VALICMSGARANTIDOINTEGRAL;
                SET LDE_VALICMS      = 0;
            ELSE
                SET LDE_VALGINTEGRAL=0;
            END IF;
        END IF;
        SET LS_FLAGMOVCUSMEDIO = AS_FLAGMOVCUSMEDIO;
        SET LDE_VALPIS         = AD_VALPIS;
        SET LDE_VALCOFINS      = AD_VALCOFINS;
        SET LS_TIPOPISCOFINS   = AS_TIPOPISCOFINS;
        IF LS_TIPOPISCOFINS <> 'N' THEN
            IF LDE_VALPIS > 0 THEN
                SET LDE_VALPIS = 0;
            END IF;
            IF LDE_VALCOFINS > 0 THEN
                SET LDE_VALCOFINS = 0;
            END IF;
        END IF;
        IF AS_TIPOBAIXAMESTRE = 'M' THEN
            SET LI_IDSUBPRODUTO = LI_IDPRODUTO;
        END IF;
        IF COALESCE(LS_LOG_VARIACAO_CMV, 'F') = 'T' THEN
            SET LDE_CMV_OLD = DBA.UF_BUSCACUSTOMEDIO(
                                      LI_IDEMPRESA,
                                      LI_IDPRODUTO,
                                      LI_IDSUBPRODUTO,
                                      LI_IDLOCALESTOQUE,
                                      LD_DTMOVIMENTO );
        END IF;
        CALL DBA.SP_PROCESSA_SALDO(
            LI_IDEMPRESA,
            LI_IDEMPRESANOTA,
            LI_IDPLANILHA,
            LI_NUMSEQUENCIA,
            LI_IDPRODUTO,
            LI_IDSUBPRODUTO,
            LI_IDLOCALESTOQUE,
            LD_DTMOVIMENTO,
            LDE_QTDPRODUTO,
            LDE_VALTOTLIQUIDO,
            LS_TIPOCATEGORIA,
            LS_FLAGMOVCONTABIL,
            LS_FLAGMOVSALDOPRO,
            LS_FLAGCALCULOGIRO,
            LDE_VALFRETECONHEC,
            LDE_VALICMS,
            LI_IDOPERACAO,
            LS_FLAGMOVCUSMEDIO,
            LDE_VALPIS,
            LDE_VALCOFINS,
            LDE_VALSFRONTEIRA,
            LDE_VALGINTEGRAL,
            LS_TIPOITEMCATEGORIA,
            LS_IDLOTE,
            LDE_VALTAXASDIVERSAS,
            LDE_VALDIFSUBSTAJUSTADO,
            LDE_VALBONIFICACAO,
            LS_FLAGPRECOPROMOCAO,
            AI_IDSITTRIB
        );

        -- APAGA O REGISTRO DE PROCESSADO ANTES DE TENTAR INSERIR OUTRO
        DELETE FROM DBA.ESTOQUE_ANALITICO_SALDO_PROCESSADO
        WHERE IDEMPRESA = LI_IDEMPRESANOTA
        AND IDPLANILHA = LI_IDPLANILHA
        AND NUMSEQUENCIA = LI_NUMSEQUENCIA
        ;

        -- MARCA O REGISTRO COMO PROCESSADO
        INSERT INTO DBA.ESTOQUE_ANALITICO_SALDO_PROCESSADO(IDEMPRESA,IDPLANILHA,NUMSEQUENCIA)
        VALUES(LI_IDEMPRESANOTA,LI_IDPLANILHA,LI_NUMSEQUENCIA);
        DELETE FROM DBA.ESTOQUE_ANALITICO_SALDO_PROCESSAR
        WHERE IDEMPRESA=LI_IDEMPRESANOTA AND IDPLANILHA=LI_IDPLANILHA AND NUMSEQUENCIA=LI_NUMSEQUENCIA;

        IF LDE_CMV_OLD > 0 AND LDE_CMV_NEW <> LDE_CMV_OLD THEN
            SET LDE_PERVARIACAO = CAST( ( LDE_CMV_NEW * 100 ) / LDE_CMV_OLD AS DECIMAL(15,6)) - 100;
            SET LI_IDUSUARIO = ( SELECT
                                    NOTAS.IDUSUARIO
                                 FROM
                                    DBA.NOTAS
                                 WHERE
                                    NOTAS.IDEMPRESA  = LI_IDEMPRESA AND
                                    NOTAS.IDPLANILHA = LI_IDPLANILHA
                                );
            INSERT INTO DBA.LOG_VARIACAO_CMV (
                EVENT,
                IDEMPRESA,
                IDPLANILHA,
                NUMSEQUENCIA,
                IDOPERACAO,
                IDPRODUTO,
                IDSUBPRODUTO,
                TIPOBAIXAMESTRE,
                QTDPRODUTO_OLD,
                QTDPRODUTO_NEW,
                VALTOTLIQUIDO_OLD,
                VALTOTLIQUIDO_NEW,
                IP,
                DTHORA,
                CMV_OLD,
                CMV_NEW,
                PERVARIACAO,
                IDUSUARIO
            ) VALUES (
                'I',
                LI_IDEMPRESA,
                LI_IDPLANILHA,
                LI_NUMSEQUENCIA,
                LI_IDOPERACAO,
                LI_IDPRODUTO,
                LI_IDSUBPRODUTO,
                AS_TIPOBAIXAMESTRE,
                NULL,
                LDE_QTDPRODUTO,
                NULL,
                LDE_VALTOTLIQUIDO,
                APPLICATION_ID(),
                CURRENT TIMESTAMP,
                LDE_CMV_OLD,
                LDE_CMV_NEW,
                LDE_PERVARIACAO,
                LI_IDUSUARIO
            );
        END IF;
    END IF;
END
