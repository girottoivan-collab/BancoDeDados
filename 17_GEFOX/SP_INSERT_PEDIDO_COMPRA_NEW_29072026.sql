CREATE OR REPLACE FUNCTION DBA.UF_GET_COI_PEDIDO_COMPRA_LIBERADO (
	AI_IDEMPRESA INTEGER,
	AI_IDCLIFOR INTEGER
)
RETURNS INTEGER
LANGUAGE SQL
READS SQL DATA
BEGIN ATOMIC
	DECLARE LI_IDOPERACAO INTEGER;

	SET LI_IDOPERACAO = (
		SELECT
			CF.IDOPERACAOPADRAO
		FROM
			DBA.CLIENTE_FORNECEDOR CF
		JOIN
			DBA.OPERACAO_INTERNA OI ON
				OI.IDOPERACAO = CF.IDOPERACAOPADRAO
		WHERE
			CF.IDCLIFOR = AI_IDCLIFOR AND
			OI.TIPOCATEGORIA = 'C' AND
			OI.TIPOITEMCATEGORIA = 'C1' AND
			NOT EXISTS (
				SELECT
					1
				FROM
					DBA.EMPRESA_BLOQUEIO_COI EBC
				WHERE
					EBC.IDEMPRESA = AI_IDEMPRESA AND
					EBC.IDOPERACAO = OI.IDOPERACAO
			)
		FETCH FIRST 1 ROW ONLY
	);

	IF LI_IDOPERACAO IS NOT NULL THEN
		RETURN LI_IDOPERACAO;
	END IF;

	SET LI_IDOPERACAO = (
		SELECT
			CC.IDCOIPADRAOPEDIDOCOMPRA
		FROM
			DBA.CONFIG_COMPRAS CC
		JOIN
			DBA.OPERACAO_INTERNA OI ON
				OI.IDOPERACAO = CC.IDCOIPADRAOPEDIDOCOMPRA
		WHERE
			OI.TIPOCATEGORIA = 'C' AND
			OI.TIPOITEMCATEGORIA = 'C1' AND
			NOT EXISTS (
				SELECT
					1
				FROM
					DBA.EMPRESA_BLOQUEIO_COI EBC
				WHERE
					EBC.IDEMPRESA = AI_IDEMPRESA AND
					EBC.IDOPERACAO = OI.IDOPERACAO
			)
		FETCH FIRST 1 ROW ONLY
	);

	IF LI_IDOPERACAO IS NOT NULL THEN
		RETURN LI_IDOPERACAO;
	END IF;

	SET LI_IDOPERACAO = (
		SELECT
			MIN(OI.IDOPERACAO)
		FROM
			DBA.OPERACAO_INTERNA OI
		WHERE
			OI.TIPOCATEGORIA = 'C' AND
			OI.TIPOITEMCATEGORIA = 'C1' AND
			NOT EXISTS (
				SELECT
					1
				FROM
					DBA.EMPRESA_BLOQUEIO_COI EBC
				WHERE
					EBC.IDEMPRESA = AI_IDEMPRESA AND
					EBC.IDOPERACAO = OI.IDOPERACAO
			)
	);

	RETURN LI_IDOPERACAO;
END
GO
GRANT EXECUTE ON FUNCTION DBA.UF_GET_COI_PEDIDO_COMPRA_LIBERADO TO USER GEA
GO
